// server.js
const express = require("express"); // подключаем библиотеку Express
const app = express(); // создаём приложение — это и есть наш будущий сервер


const PORT = 3000; // на каком порту сервер будет слушать запросы
// Простейший маршрут: GET-запрос на "/" (главная) — отвечаем текстом.
// 
// 
app.get("/", function (req, res) {
  // req — то, что нам прислали (запрос); res — то, чем мы отвечаем
  res.send("Сервер работает!");
});

// app.listen запускается ПОСЛЕДНИМ, когда все маршруты уже описаны —
// он «включает» сервер и заставляет его слушать порт.
app.listen(PORT, function () {
  console.log(`Сервер запущен на http://localhost:${PORT}`);
});