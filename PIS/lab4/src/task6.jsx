import { useState } from "react";

const products = [
  "Абонемент на месяц",
  "Разовое занятие",
  "Персональная тренировка",
];

const navItems = ["Расписание", "Тренеры", "Цены"];

const initialCatalog = [
  { name: "Абонемент на месяц", price: "2500 ₽" },
  { name: "Разовое занятие", price: "500 ₽" },
  { name: "Персональная тренировка", price: "1500 ₽" },
];

function App() {
  // TODO 6: каталог храним в state, чтобы элементы можно было удалять
  const [catalog, setCatalog] = useState(initialCatalog);

  function removeProduct(index) {
    setCatalog((prev) => prev.filter((_, i) => i !== index));
  }

  return (
    <div>
      <h1>Спортивный клуб «Атлет»</h1>

      {/* TODO 1: список через .map() с key */}
      <h2>Товары</h2>
      <ul>
        {products.map((name, index) => (
          <li key={index}>{name}</li>
        ))}
      </ul>

      {/* TODO 3: список кнопок навигации */}
      <h2>Меню</h2>
      <nav>
        {navItems.map((item, index) => (
          <button key={index}>{item}</button>
        ))}
      </nav>

      {/* TODO 5: список карточек с двумя полями */}
      <h2>Каталог</h2>
      <ul>
        {catalog.map((product, index) => (
          <li key={index}>
            <strong>{product.name}</strong> — {product.price}
            {/* TODO 6: удаление по индексу через filter */}
            <button onClick={() => removeProduct(index)}>Удалить</button>
          </li>
        ))}
      </ul>
    </div>
  );
}

export default App;

// TODO 2: Забытый key
// React пишет в консоль предупреждение "Each child in a list should have a
// unique 'key' prop": без key React не может сопоставить элементы списка
// между рендерами и вынужден перерисовывать их менее эффективно (а при
// изменении порядка может перепутать состояние строк/компонентов).

// TODO 4: Почему Math.random() как key — плохая идея
// При каждом рендере Math.random() даёт новое число, поэтому React считает,
// что весь список полностью новый. Все элементы удаляются и создаются
// заново: теряются DOM-узлы, состояние внутри них, анимации и фокус, а
// производительность падает из-за лишней работы на каждое обновление state.

// TODO 6 (продолжение): Когда index как key опасен
// При удалении элемента из середины списка индексы сдвигаются: React
// сопоставляет элементы по key=index и решает, что изменился последний
// элемент, хотя удалили средний. В результате может "переехать" состояние
// (например, текст в input или галочка) от одного товара к другому. Если бы
// у товаров были собственные уникальные id, использовали бы key={product.id} —
// он остаётся неизменным при удалении и React корректно находит нужный элемент.

// TODO 7: Зачем React вообще нужен key
// key — это "бирка" элемента списка. Сравнивая старый и новый списки, React
// по key понимает, какие элементы остались теми же (их можно просто
// обновить), какие появились, а какие удалены. Без key (или при
// нестабильном key) такое сопоставление невозможно.
