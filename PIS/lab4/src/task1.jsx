// TODO 1: Компонент-функция
// Функциональный компонент Header возвращает <h1> с названием клуба.
function Header() {
  return <h1>Спортивный клуб «Атлет»</h1>;
}

// TODO 2: Один корневой элемент
// Почему сломанный Nav не работает: return возвращает два соседних элемента
// (<h2> и <p>) без общей обёртки, а JSX требует ровно один корневой элемент,
// потому что компилятор превращает разметку в один вызов React.createElement.
// Исправление — обернуть всё в один корневой <nav className="menu">.
function Nav() {
  return (
    <nav className="menu">
      <h2>Меню</h2>
      <p Выберите раздел />
      <a href="#" Расписание />
      <a href="#" Тренеры />
      <a href="#" Цены />
    </nav>
  );
}

// TODO 3: class -> className
// В JSX вместо class пишут className (class — зарезервированное слово JS).
// Класс "menu" уже добавлен на <nav> в компоненте Nav выше.

// --- Сложный уровень ---



// TODO 6: Всё вместе — карточка товара
function ProductCard() {
  const productName = "Абонемент на месяц";

  return (
    <div className="product-card">
      <h2>{productName}</h2>
      <p>2500 ₽</p>
      <img src="/product.png" alt="" className="product-img" />
    </div>
  );
}

function App() {
  // TODO 4: {} для JS-переменной
  const shopName = "Спортивный клуб «Атлет»";

  return (
    <div>
      {/* TODO 5: самозакрывающийся тег картинки */}
      <img src="/logo.png" alt="Спортивный клуб «Атлет»" />

      <Header />

      <h1>{shopName}</h1>
      <Nav />
      <ProductCard />
    </div>
  );
}

export default App;

